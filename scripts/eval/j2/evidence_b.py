    assert d(2024, 7, 20).toordinal() - 2 == d(2024, 7, 18).toordinal()        # k27: "the day before yesterday" on 7/20
    assert (d(2024, 12, 8) - d(2024, 11, 17)).days == 21                       # k28
    assert d(2024, 11, 9).weekday() == 5 and d(2024, 11, 10).weekday() == 6     # k33: last weekend before Friday 11/15
    assert d(2024, 11, 15).weekday() == 4
